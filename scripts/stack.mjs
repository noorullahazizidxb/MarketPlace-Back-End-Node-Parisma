#!/usr/bin/env node
import fs from 'fs';
import path from 'path';
import readline from 'readline';
import { spawn } from 'child_process';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const backendRoot = path.resolve(__dirname, '..');
const envPath = path.join(backendRoot, '.env');
const lockPath = path.join(backendRoot, '.stack.lock');

const DEFAULT_ADMIN_EMAIL = 'admin@example.com';
const DEFAULT_ADMIN_PASSWORD = 'MarketPlace@2026';
const DEFAULT_TOKEN_SECRET = 'dev_secret_change_me';

function defaultFrontendPath() {
  if (process.env.FRONTEND_PATH) return path.resolve(process.env.FRONTEND_PATH);
  const sibling = path.resolve(backendRoot, '..', 'MarketPlace-Next-JS');
  return sibling;
}

function parseArgs() {
  const args = new Set(process.argv.slice(2));
  return {
    setupOnly: args.has('--setup-only'),
    reset: args.has('--reset-stack'),
    defaults: args.has('--defaults'),
  };
}

function question(rl, prompt, fallback = '') {
  return new Promise((resolve) => {
    const suffix = fallback ? ` [${fallback}]` : '';
    rl.question(`${prompt}${suffix}: `, (answer) => {
      resolve(String(answer || '').trim() || fallback);
    });
  });
}

async function yesNo(rl, prompt, defaultYes = true) {
  const def = defaultYes ? 'Y/n' : 'y/N';
  const answer = await question(rl, `${prompt} (${def})`);
  if (!answer) return defaultYes;
  return ['y', 'yes', '1', 'true'].includes(answer.toLowerCase());
}

function quoteEnv(value) {
  const str = String(value ?? '');
  if (/[\s#"'=]/.test(str)) return `"${str.replace(/"/g, '\\"')}"`;
  return str;
}

function writeEnvFile(filePath, values) {
  const lines = ['# Generated by scripts/stack.mjs — edit as needed', ''];
  for (const [key, value] of Object.entries(values)) {
    if (value === undefined || value === null) continue;
    lines.push(`${key}=${quoteEnv(value)}`);
  }
  fs.writeFileSync(filePath, `${lines.join('\n')}\n`, 'utf8');
}

function loadDotEnv(filePath) {
  if (!fs.existsSync(filePath)) return {};
  const out = {};
  for (const line of fs.readFileSync(filePath, 'utf8').split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eq = trimmed.indexOf('=');
    if (eq === -1) continue;
    let val = trimmed.slice(eq + 1).trim();
    if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) {
      val = val.slice(1, -1);
    }
    out[trimmed.slice(0, eq).trim()] = val;
  }
  return out;
}

function applyEnv(values) {
  for (const [key, value] of Object.entries(values)) {
    if (value === undefined || value === null) continue;
    process.env[key] = String(value);
  }
}

function run(cmd, args, opts = {}) {
  return new Promise((resolve, reject) => {
    const child = spawn(cmd, args, { stdio: 'inherit', shell: true, cwd: backendRoot, ...opts });
    child.on('exit', (code) => {
      if (code === 0) resolve();
      else reject(new Error(`${cmd} ${args.join(' ')} exited with code ${code}`));
    });
  });
}

function normalizeDbProvider(raw) {
  let dbProvider = String(raw || '').trim().toLowerCase();
  if (dbProvider === 'postgres') dbProvider = 'postgresql';
  if (!['sqlite', 'mysql', 'postgresql'].includes(dbProvider)) {
    console.log('Unknown database, defaulting to sqlite');
    return 'sqlite';
  }
  return dbProvider;
}

function applyVercelConstraints(cfg) {
  if (cfg.hosting !== 'vercel') return cfg;
  if (cfg.redisEnabled || cfg.searchEnabled) {
    console.log('\nVercel cannot run Redis, Elasticsearch, Socket.IO, or BullMQ.');
    console.log('Those add-ons are stored as requested but forced off in generated env.\n');
  }
  if (cfg.dbProvider === 'sqlite') {
    console.log('Warning: a local SQLite file will not persist on real Vercel. Prefer Neon Postgres.');
  }
  return { ...cfg, redisEnabled: false, searchEnabled: false };
}

function defaultCfg() {
  return {
    hosting: 'local',
    dbProvider: 'sqlite',
    databaseUrl: '',
    sqliteUrl: 'file:./dev.db',
    redisEnabled: false,
    redisUrl: 'redis://127.0.0.1:6379',
    searchEnabled: false,
    esUrl: '',
    jwtSecret: DEFAULT_TOKEN_SECRET,
    corsOrigin: '*',
    seed: true,
    adminEmail: DEFAULT_ADMIN_EMAIL,
    adminPassword: DEFAULT_ADMIN_PASSWORD,
  };
}

async function promptDatabase(rl) {
  let dbProvider = normalizeDbProvider(
    await question(rl, '1) Primary database (sqlite / mysql / postgresql)', 'sqlite'),
  );
  let databaseUrl = '';
  let sqliteUrl = 'file:./dev.db';
  if (dbProvider === 'sqlite') {
    sqliteUrl = await question(rl, 'SQLite file URL', 'file:./dev.db');
  } else if (dbProvider === 'mysql') {
    databaseUrl = await question(rl, 'DATABASE_URL', 'mysql://root:password@127.0.0.1:3306/marketplace');
  } else {
    databaseUrl = await question(rl, 'DATABASE_URL', 'postgresql://user:password@127.0.0.1:5432/marketplace');
  }
  return { dbProvider, databaseUrl, sqliteUrl };
}

async function promptRedis(rl) {
  const redisEnabled = await yesNo(rl, '2) Enable Redis (cache, rate limit, queues)?', false);
  const redisUrl = redisEnabled
    ? await question(rl, 'REDIS_URL', 'redis://127.0.0.1:6379')
    : 'redis://127.0.0.1:6379';
  return { redisEnabled, redisUrl };
}

async function promptElasticsearch(rl) {
  const searchEnabled = await yesNo(rl, '3) Enable Elasticsearch?', false);
  const esUrl = searchEnabled
    ? await question(rl, 'ELASTICSEARCH_URL', 'http://127.0.0.1:9200')
    : '';
  return { searchEnabled, esUrl };
}

async function wizard() {
  const rl = readline.createInterface({ input: process.stdin, output: process.stdout });
  console.log('\nMarketplace stack setup (first run)\n');
  console.log('SQLite / MySQL / PostgreSQL are alternative primary databases.');
  console.log('Redis and Elasticsearch are optional add-ons (forced off on Vercel).\n');

  const db = await promptDatabase(rl);
  const redis = await promptRedis(rl);
  const search = await promptElasticsearch(rl);

  const hostingRaw = (await question(rl, 'Hosting platform (local / vercel)', 'local')).toLowerCase();
  const hosting = hostingRaw === 'vercel' ? 'vercel' : 'local';
  const jwtSecret = await question(rl, 'TOKEN_SECRET', DEFAULT_TOKEN_SECRET);
  const corsOrigin = await question(
    rl,
    'CORS_ORIGIN',
    hosting === 'vercel' ? 'https://marketplace.devminds.net' : '*',
  );
  const seed = await yesNo(rl, 'Run database seed after migrate?', true);
  rl.close();

  return applyVercelConstraints({
    hosting,
    ...db,
    ...redis,
    ...search,
    jwtSecret,
    corsOrigin,
    seed,
    adminEmail: DEFAULT_ADMIN_EMAIL,
    adminPassword: DEFAULT_ADMIN_PASSWORD,
  });
}

function backendEnvFrom(cfg) {
  const vercel = cfg.hosting === 'vercel';
  const redisOn = Boolean(cfg.redisEnabled) && !vercel;
  const searchOn = Boolean(cfg.searchEnabled) && !vercel;
  const env = {
    HOSTING_PLATFORM: cfg.hosting,
    PORT: '4000',
    NODE_ENV: vercel ? 'production' : 'development',
    DB_PROVIDER: cfg.dbProvider,
    DATABASE_URL: cfg.databaseUrl || '',
    SQLITE_URL: cfg.sqliteUrl || 'file:./dev.db',
    REDIS_ENABLED: redisOn ? 'true' : 'false',
    REDIS_URL: cfg.redisUrl || 'redis://127.0.0.1:6379',
    SEARCH_ENABLED: searchOn ? 'true' : 'false',
    ENABLE_ELASTIC_SEARCH: searchOn ? 'true' : 'false',
    SOCKET_IO_ENABLED: vercel ? 'false' : 'true',
    TOKEN_SECRET: cfg.jwtSecret || DEFAULT_TOKEN_SECRET,
    JWT_SECRET: cfg.jwtSecret || DEFAULT_TOKEN_SECRET,
    CORS_ORIGIN: cfg.corsOrigin || '*',
    FRONTEND_URL: vercel ? 'https://marketplace.devminds.net' : 'http://localhost:3000',
    JSON_LIMIT: '10mb',
    URLENCODED_LIMIT: '10mb',
    QUEUE_PREFIX: 'marketplace',
    ADMIN_EMAIL: cfg.adminEmail || DEFAULT_ADMIN_EMAIL,
    ADMIN_PASSWORD: cfg.adminPassword || DEFAULT_ADMIN_PASSWORD,
    SEED_USER_PASSWORD: cfg.adminPassword || DEFAULT_ADMIN_PASSWORD,
    CRON_SECRET: '',
  };
  if (cfg.esUrl) {
    env.ELASTICSEARCH_URL = cfg.esUrl;
    env.ELASTICSEARCH_NODE = cfg.esUrl;
  }
  return env;
}

function frontendEnvFrom(cfg) {
  const vercel = cfg.hosting === 'vercel';
  const searchOn = Boolean(cfg.searchEnabled) && !vercel;
  const apiBase = vercel
    ? 'https://marketplace.devminds.net/backend/api'
    : 'http://localhost:4000/api';
  const env = {
    NEXT_PUBLIC_SITE_URL: vercel ? 'https://marketplace.devminds.net' : 'http://localhost:3000',
    NEXT_PUBLIC_API_BASE: apiBase,
    NEXT_PUBLIC_API_BASE_URL: apiBase,
    NEXT_PUBLIC_API_HOST: vercel ? 'https://marketplace.devminds.net' : 'http://localhost:4000',
    NEXT_PUBLIC_WS_URL: vercel ? 'https://marketplace.devminds.net' : 'http://localhost:4000',
    NEXT_PUBLIC_SOCKET_URL: vercel ? 'https://marketplace.devminds.net' : 'http://localhost:4000',
    NEXT_PUBLIC_SOCKET_IO_ENABLED: vercel ? 'false' : 'true',
    NEXT_PUBLIC_ENABLE_ELASTIC_SEARCH: searchOn ? 'true' : 'false',
    BACKEND_VERCEL_URL: vercel ? '' : '',
    PORT: '3000',
  };
  if (searchOn && cfg.esUrl) {
    env.ELASTICSEARCH_NODE = cfg.esUrl;
    env.ELASTICSEARCH_URL = cfg.esUrl;
    env.SEARCH_ENABLED = 'true';
  }
  return env;
}

function writeLock(cfg) {
  fs.writeFileSync(lockPath, `${JSON.stringify({
    createdAt: new Date().toISOString(),
    hosting: cfg.hosting,
    dbProvider: cfg.dbProvider,
    redisEnabled: Boolean(cfg.redisEnabled),
    searchEnabled: Boolean(cfg.searchEnabled),
  }, null, 2)}\n`, 'utf8');
}

function cfgFromEnv(env) {
  return {
    hosting: env.HOSTING_PLATFORM || 'local',
    dbProvider: env.DB_PROVIDER || 'mysql',
    databaseUrl: env.DATABASE_URL || '',
    sqliteUrl: env.SQLITE_URL || 'file:./dev.db',
    redisEnabled: env.REDIS_ENABLED !== 'false' && env.HOSTING_PLATFORM !== 'vercel',
    redisUrl: env.REDIS_URL || 'redis://127.0.0.1:6379',
    searchEnabled: (env.SEARCH_ENABLED === 'true' || env.ENABLE_ELASTIC_SEARCH === 'true') && Boolean(env.ELASTICSEARCH_URL || env.ELASTICSEARCH_NODE),
    esUrl: env.ELASTICSEARCH_URL || env.ELASTICSEARCH_NODE || '',
    jwtSecret: env.TOKEN_SECRET || env.JWT_SECRET || DEFAULT_TOKEN_SECRET,
    corsOrigin: env.CORS_ORIGIN || '*',
    seed: false,
    adminEmail: env.ADMIN_EMAIL || DEFAULT_ADMIN_EMAIL,
    adminPassword: env.ADMIN_PASSWORD || env.SEED_USER_PASSWORD || DEFAULT_ADMIN_PASSWORD,
  };
}

async function prismaSetup(envValues, seed) {
  applyEnv(envValues);
  const childEnv = { ...process.env, ...envValues };
  console.log(`\nGenerating Prisma client (${envValues.DB_PROVIDER})...`);
  await run('npx', ['prisma', 'generate'], { env: childEnv });
  console.log('Applying migrations...');
  await run('npx', ['prisma', 'migrate', 'deploy'], { env: childEnv });
  if (seed) {
    console.log('Seeding database...');
    try {
      await run('npm', ['run', 'seed:all'], { env: childEnv });
    } catch (err) {
      console.warn('Seed failed (continuing):', err.message);
    }
  }
}

function startProcess(label, cmd, args, cwd, env) {
  console.log(`Starting ${label}...`);
  const child = spawn(cmd, args, { stdio: 'inherit', shell: true, cwd, env });
  child.on('exit', (code) => {
    if (code && code !== 0) console.error(`${label} exited with code ${code}`);
  });
  return child;
}

function writeStackFiles(cfg, frontendRoot) {
  const backendEnv = backendEnvFrom(cfg);
  writeEnvFile(envPath, backendEnv);
  writeLock(cfg);
  if (fs.existsSync(path.join(frontendRoot, 'package.json'))) {
    writeEnvFile(path.join(frontendRoot, '.env'), frontendEnvFrom(cfg));
    console.log(`Wrote frontend env: ${path.join(frontendRoot, '.env')}`);
  } else {
    console.warn(`Frontend not found at ${frontendRoot}. Set FRONTEND_PATH to write its .env.`);
  }
  return backendEnv;
}

async function main() {
  const opts = parseArgs();
  const frontendRoot = defaultFrontendPath();
  const hasEnv = fs.existsSync(envPath);
  const hasLock = fs.existsSync(lockPath);
  const shouldWizard = opts.reset || (!hasLock && !hasEnv);

  let cfg;
  let backendEnv;
  if (shouldWizard) {
    if (opts.defaults) {
      cfg = defaultCfg();
      console.log('Using defaults: local SQLite, Redis off, Elasticsearch off');
    } else {
      cfg = await wizard();
    }
    backendEnv = writeStackFiles(cfg, frontendRoot);
    await prismaSetup(backendEnv, cfg.seed);
  } else {
    backendEnv = loadDotEnv(envPath);
    cfg = cfgFromEnv(backendEnv);
    if (!hasLock) writeLock(cfg);
    applyEnv(backendEnv);
    console.log(`Using existing stack: DB=${cfg.dbProvider} hosting=${cfg.hosting}`);
    console.log('Re-run first-time prompts with: npm run setup -- --reset-stack');
  }

  if (opts.setupOnly) {
    console.log('Setup complete.');
    return;
  }

  const children = [];
  children.push(startProcess('API', 'npm', ['run', 'dev'], backendRoot, { ...process.env, ...backendEnv }));
  if (fs.existsSync(path.join(frontendRoot, 'package.json'))) {
    const feEnv = {
      ...process.env,
      ...loadDotEnv(path.join(frontendRoot, '.env')),
      PORT: process.env.FRONTEND_PORT || '3000',
    };
    children.push(startProcess('frontend', 'npm', ['run', 'dev'], frontendRoot, feEnv));
  }

  const shutdown = () => {
    for (const child of children) {
      try { child.kill('SIGINT'); } catch { /* ignore */ }
    }
    process.exit(0);
  };
  process.on('SIGINT', shutdown);
  process.on('SIGTERM', shutdown);
}

main().catch((err) => {
  console.error(err.message || err);
  process.exit(1);
});
